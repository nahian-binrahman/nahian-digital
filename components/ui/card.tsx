export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean }
>(({ className, interactive = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-xl border border-stone-200/80 bg-white p-6 sm:p-8 text-stone-900 shadow-[0_1px_2px_rgba(0,0,0,0.04)] transition-all duration-200",
      interactive && "hover:border-stone-300 hover:shadow-md cursor-pointer",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

